import fs from 'node:fs'
import path from 'node:path'
import regexgen from 'regexgen'
import {expandN} from 'regex-to-strings'
import {unitsLong, unitsShort} from './src/units/definitions/parse'
import timezoneCities from './src/tokenize/timezone-cities.json'
import timezoneCountries from './src/tokenize/timezone-countries.json'

const unitsShortWithSpacesTrie = new regexgen.Trie()
unitsShortWithSpacesTrie.addAll(
  Object.values(unitsShort).map(cls => Object.values(cls)).flat()
    .filter(regex => regex.source.includes('\\s'))
    .map(regex => expandN(new RegExp(regex.source.replace(/\\s[*+]?/g, ' ')), 6)).flat()
    .filter(str => str.includes(' '))
)
const unitsShortWithSpaces = unitsShortWithSpacesTrie.toRegExp()
const unitsLongWithSpacesTrie = new regexgen.Trie()
unitsLongWithSpacesTrie.addAll(
  Object.values(unitsLong).map(cls => Object.values(cls)).flat()
    .filter(regex => regex.source.includes('\\s'))
    .map(regex => expandN(new RegExp(regex.source.replace(/\\s[*+]?/g, ' ')), 6)).flat()
    .filter(str => str.includes(' '))
)
const unitsLongWithSpaces = unitsLongWithSpacesTrie.toRegExp()

let durationShortTrie = new regexgen.Trie()
let durationLongTrie = new regexgen.Trie()
durationShortTrie.addAll(Object.values(unitsShort.duration).map(regex => expandN(regex, 10)).flat())
durationLongTrie.addAll(Object.values(unitsLong.duration).map(regex => expandN(new RegExp(regex.source), 10)).flat())
const durationShort = durationShortTrie.toRegExp()
const durationLong = durationLongTrie.toRegExp()

let tzTrie = new regexgen.Trie()
const timezoneCitiesLower = Object.fromEntries(Object.entries(timezoneCities).map(([tz, cities]) => [tz, cities.map(city => city.toLowerCase())]))
const timezoneCountriesLower = Object.fromEntries(Object.entries(timezoneCountries).map(([country, tz]) => [country.toLowerCase(), tz]))
const timeZoneLocations = Intl.supportedValuesOf('timeZone')
  .filter(tz => !tz.startsWith('Etc') && !tz.includes('UTC'))
  .map(tz => tz.split('/').at(-1)?.replaceAll('_', ' ') as string)
  .concat(Object.values(timezoneCitiesLower).flat())
  .concat(Object.keys(timezoneCountriesLower)).sort()
tzTrie.addAll(timeZoneLocations.map(s => s.toLowerCase()))
const tz = tzTrie.toRegExp()

let jsString = '/* This file is generated by generate-regex.ts */\n'
jsString += `export const unitsShortWithSpaces = /${unitsShortWithSpaces.source}/${unitsShortWithSpaces.flags}\n`
jsString += `export const unitsLongWithSpaces = /${unitsLongWithSpaces.source}/${unitsLongWithSpaces.flags}\n`
jsString += `export const durationShort = /${durationShort.source}/${durationShort.flags}\n`
jsString += `export const durationLong = /${durationLong.source}/${durationLong.flags}\n`
jsString += `export const timezoneCitiesLower: Record<string, string[]> = ${JSON.stringify(timezoneCitiesLower)}\n`
jsString += `export const timezoneCountriesLower: Record<string, string> = ${JSON.stringify(timezoneCountriesLower)}\n`
jsString += `export const tz = /${tz.source}/${tz.flags}\n`

fs.writeFileSync(path.join('src', 'tokenize', 'generated.ts'), jsString,'utf8')
